-- Журнал уведомлений: инженер видит только то, что адресовано ему.
--
-- Зачем. В журнале лежит переписка с клиентами (адреса контактов площадок), письма
-- руководителю и номера телеграм-чатов сотрудников. По ТЗ инженеру положены только
-- свои назначения и статусы его заявок — так и подписан раздел в его меню.
--
-- Правило строк из 0009 открывало весь журнал тому, у кого есть любое из трёх прав:
-- «Все задачи» (tasks.read_all), «Просмотр журнала» (audit.read) или «Настройка писем»
-- (notification_settings.write). Первое — лишнее: «видеть все задачи» и «видеть чужую
-- переписку» это разные решения, а в CRM можно собрать свою роль. Стоило выдать
-- старшему инженеру «Все задачи» — и он получал весь журнал вместе с чужими чатами,
-- хотя роль задумывалась как инженерская.
--
-- Что теперь. Весь журнал открывают только право вести журнал (audit.read) и право
-- настраивать письма (notification_settings.write). Всем остальным — строки, где
-- адресат это они сами. Встроенные роли не меняются: у координатора и руководителя
-- есть audit.read, у администратора — notification_settings.write, у системного
-- администратора — все права. Инженер, кладовщик и инициатор видят только своё.
--
-- Письма клиентам адресата-сотрудника не имеют вовсе (recipient_user_id пустой,
-- это видно по сборке адресатов в 0029), поэтому инженеру они не достаются ни по
-- какому условию.
--
-- Миграцию можно применить повторно.

DROP POLICY IF EXISTS role_read ON public.notifications;
CREATE POLICY role_read ON public.notifications
  FOR SELECT TO authenticated
  USING (
    (SELECT public.app_has_permission('notifications.read'))
    AND (
      recipient_user_id = (SELECT auth.uid())
      OR (SELECT public.app_has_any_permission(ARRAY['audit.read', 'notification_settings.write']))
    )
  );

COMMENT ON COLUMN public.notifications.recipient_user_id IS
  'Сотрудник-адресат; у писем клиентам пусто. По нему правило строк показывает журнал только адресату (0034).';
